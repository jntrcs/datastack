-- Snowflake foundation: warehouses, databases, roles, cost guardrail.
-- Idempotent: safe to re-run.  uv run python -m warehouse.sf -f warehouse/sql/01_foundation.sql
--
-- Pattern (the common "dbt-style" Snowflake layout):
--   LOADER       writes RAW            using LOADING_WH       (pipelines)
--   TRANSFORMER  reads RAW, owns ANALYTICS  using TRANSFORMING_WH  (dbt)
--   REPORTER     reads ANALYTICS       using REPORTING_WH     (dashboards/analysts)
-- One warehouse per workload so each one's cost shows up separately on the bill.

USE ROLE ACCOUNTADMIN;

-- Cost guardrail: hard stop at 10 credits/month (~$20 on Standard). The trial
-- has ~$400 of credits; this workload should use well under 1 credit/month.
CREATE RESOURCE MONITOR IF NOT EXISTS DATASTACK_MONTHLY
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LOADING_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORMING_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS REPORTING_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RAW COMMENT = 'Untouched source data, loaded from R2. Never edited.';
CREATE SCHEMA IF NOT EXISTS RAW.APP_STORE;
CREATE SCHEMA IF NOT EXISTS RAW.CLOUDFLARE;
CREATE SCHEMA IF NOT EXISTS RAW.LANDING COMMENT = 'Stages and file formats pointing at R2.';
CREATE DATABASE IF NOT EXISTS ANALYTICS COMMENT = 'Everything built by dbt.';

USE ROLE ACCOUNTADMIN;
ALTER WAREHOUSE LOADING_WH      SET RESOURCE_MONITOR = DATASTACK_MONTHLY;
ALTER WAREHOUSE TRANSFORMING_WH SET RESOURCE_MONITOR = DATASTACK_MONTHLY;
ALTER WAREHOUSE REPORTING_WH    SET RESOURCE_MONITOR = DATASTACK_MONTHLY;

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS REPORTER;
-- Roll the custom roles up to SYSADMIN (Snowflake best practice) and to you.
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;
GRANT ROLE LOADER      TO USER "<your_user_name>";
GRANT ROLE TRANSFORMER TO USER "<your_user_name>";
GRANT ROLE REPORTER    TO USER "<your_user_name>";

-- LOADER: run on LOADING_WH, create/write anything in RAW.
GRANT USAGE ON WAREHOUSE LOADING_WH TO ROLE LOADER;
GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON ALL SCHEMAS IN DATABASE RAW TO ROLE LOADER;
GRANT ALL ON ALL TABLES IN DATABASE RAW TO ROLE LOADER;
GRANT ALL ON FUTURE TABLES IN DATABASE RAW TO ROLE LOADER;

-- TRANSFORMER: read RAW, build anything in ANALYTICS.
GRANT USAGE ON WAREHOUSE TRANSFORMING_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE ANALYTICS TO ROLE TRANSFORMER;

-- REPORTER: read ANALYTICS only (dbt grants on what it builds; see Step 3).
GRANT USAGE ON WAREHOUSE REPORTING_WH TO ROLE REPORTER;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;
